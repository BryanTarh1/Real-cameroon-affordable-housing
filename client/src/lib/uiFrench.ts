const orderedEnglishTerms = Object.keys(interfaceFrench).sort((left, right) => right.length - left.length);

export function translateAhcInterfaceText(value: string, language: "en" | "fr") {
  if (language === "en" || !value.trim()) return value;
  let translated = value;
  for (const english of orderedEnglishTerms) {
    if (!translated.includes(english)) continue;
    translated = translated.split(english).join(interfaceFrench[english]);
  }
  return translated;
}

export function isAhcInterfaceTranslation(value: string) {
  return orderedEnglishTerms.some(english => value.includes(english));
}
